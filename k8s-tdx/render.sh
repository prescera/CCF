#!/usr/bin/env bash
# Render the manifest for a single CCF node running as Platform::TDX inside a
# Kata Confidential Containers Trust Domain.
#
# This is lab scaffolding for exercising the TDX attestation path on real
# hardware, not a production deployment. It mirrors the equivalent directory in
# the Transparency Service repo, which solved the same guest-pull, DNS, initdata
# and addressing problems first.
set -euo pipefail

NAMESPACE=${NAMESPACE:-ccf-tdx}
REGISTRY=${REGISTRY:-localhost:5000}
IMAGE=${IMAGE:?set IMAGE to the pushed node image, e.g. $REGISTRY/ccf-tdx:v4}
RUNTIME_CLASS=${RUNTIME_CLASS:-kata-qemu-tdx}
WORKSPACE=${WORKSPACE:?set WORKSPACE to the directory holding member0_cert.pem}
OUT=${OUT:-$(dirname "$0")/ccf-tdx.yaml}
REGISTRY_CA=${REGISTRY_CA:-/etc/docker/certs.d/$REGISTRY/ca.crt}
# Pinned before the node starts so it can go into the node certificate's SANs,
# which lets a client verify the service certificate properly instead of
# falling back to -k. Also works around `kubectl port-forward`, which cannot
# reach a Kata pod: it dials localhost in the *host* netns while the listener
# lives inside the guest VM.
CLUSTER_IP=${CLUSTER_IP:-10.43.22.61}

# The TDX runtime class pulls the image *inside* the guest, so the guest has to
# trust the cluster registry's self-signed CA. initdata is the only channel into
# a TD before any container exists. Setting it also sets
# MRCONFIGID = sha384(initdata document), so the registry trust the node booted
# with is itself a measured, attestable property of the TD.
#
# Two things fail with no useful diagnostic (sandbox dies with "timed out
# connecting to vsock"): `kbc` is required even with no KBS in use, and the
# inline `registry_config` field must be left alone.
INITDATA_B64=$(REGISTRY_CA="$REGISTRY_CA" python3 - <<'PYEOF'
import base64, gzip, hashlib, os, sys, tomllib
ca = open(os.environ["REGISTRY_CA"]).read().strip()
doc = (
    'algorithm = "sha384"\n'
    'version = "0.1.0"\n\n'
    '[data]\n'
    '"cdh.toml" = \'\'\'\n'
    '[kbc]\n'
    'name = "offline_fs_kbc"\n'
    'url = ""\n\n'
    '[image]\n'
    f'extra_root_certificates = ["""\n{ca}\n"""]\n'
    '\'\'\'\n'
)
tomllib.loads(tomllib.loads(doc)["data"]["cdh.toml"])   # fail here, not in the guest
raw = doc.encode()
print(base64.b64encode(gzip.compress(raw)).decode())
print(f"initdata sha384 (MRCONFIGID) = {hashlib.sha384(raw).hexdigest()}", file=sys.stderr)
PYEOF
)

# `awk 1` guarantees a trailing newline; without it a file that lacks one glues
# the next YAML key onto its last line and that key silently disappears.
indent() { awk 1 | sed 's/^/    /'; }

{
cat <<EOF
# GENERATED by k8s-tdx/render.sh -- edit render.sh, not this file.
apiVersion: v1
kind: ConfigMap
metadata:
  name: ccf-tdx-bootstrap
  namespace: $NAMESPACE
data:
EOF

for pem in member0_cert.pem member0_enc_pubk.pem; do
  echo "  $pem: |"
  indent < "$WORKSPACE/$pem"
done

cat <<EOF
---
apiVersion: v1
kind: Service
metadata:
  name: ccf-tdx
  namespace: $NAMESPACE
spec:
  clusterIP: $CLUSTER_IP
  selector: { app: ccf-tdx }
  ports:
    - { name: rpc, port: 8000, targetPort: 8000 }
    - { name: n2n, port: 8001, targetPort: 8001 }
---
apiVersion: v1
kind: Pod
metadata:
  name: ccf-tdx
  namespace: $NAMESPACE
  labels: { app: ccf-tdx }
  annotations:
    io.katacontainers.config.hypervisor.cc_init_data: "$INITDATA_B64"
spec:
  runtimeClassName: $RUNTIME_CLASS
  restartPolicy: Never
  initContainers:
    # cchost writes the service certificate, ledger and snapshots next to its
    # config, and a ConfigMap mount is read-only, so stage into a writable
    # volume first.
    - name: stage
      image: $IMAGE
      command:
        - sh
        - -c
        - |
          set -eux
          mkdir -p /host/ledger /host/snapshots
          cp /bootstrap/member0_cert.pem /bootstrap/member0_enc_pubk.pem /host/
          ls -l /host
      volumeMounts:
        - { name: bootstrap, mountPath: /bootstrap, readOnly: true }
        - { name: host, mountPath: /host }
  containers:
    - name: cchost
      image: $IMAGE
      # configfs is not mounted in the container by default, so the kernel's TSM
      # report interface (/sys/kernel/config/tsm/report) -- the only way to ask
      # the TD for a quote -- is invisible and CCF falls back to
      # Platform::Virtual. Mounting it needs CAP_SYS_ADMIN. This is privilege
      # *inside the guest VM*, which is itself inside the TEE, so it does not
      # weaken the TD boundary; the host still cannot see in.
      command:
        - sh
        - -c
        - |
          set -eu
          mount -t configfs none /sys/kernel/config
          test -d /sys/kernel/config/tsm/report
          exec cchost --config /opt/ccf-tdx/node-config.json
      securityContext:
        capabilities:
          add: [SYS_ADMIN]
      workingDir: /host
      ports:
        - { name: rpc, containerPort: 8000 }
        - { name: n2n, containerPort: 8001 }
      volumeMounts:
        - { name: host, mountPath: /host }
      resources:
        # Kata sizes the guest VM from these, so the TD gets what is asked for
        # here and nothing more.
        requests: { cpu: "2", memory: 2Gi }
        limits: { cpu: "2", memory: 4Gi }
  volumes:
    - name: bootstrap
      configMap: { name: ccf-tdx-bootstrap }
    - name: host
      emptyDir: {}
EOF
} > "$OUT"

echo "wrote $OUT"
